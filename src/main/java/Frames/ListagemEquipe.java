public void preencherTabela(List<Manicure> manicure){
    String columns[] = {"ID","Nome","Gmail","Telefone","Nascimento"};
    
    if(manicure != null){
        String dados[][] = new String [manicure.size()][columns.length];
        int i = 0;
        for (Manicure m : manicure){
            dados[i] = new String[]{
                String.valueOf(m.getIdManicure()),
                m.getNome(),
                m.getGmail(),
                m.getTelefone(),
                m.getData_Nascimento()
            };
            i++;
        }
        DefaultTableModel model = new DefaultTableModel(dados,columns);
        tblManicure.setModel(model);
    }
}

