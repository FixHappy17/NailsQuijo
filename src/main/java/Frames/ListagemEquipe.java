    private void btExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btExcluirActionPerformed
        try{
            if(tblManicure.getSelectedRow() >= 0){// verifica se há algo selecionado na tabela
                String id = tblManicure.getValueAt(tblManicure.getSelectedRow(), 0).toString();
                
                // Janela de confirmação
                int resposta = JOptionPane.showConfirmDialog(this,"Deseja mesmo excluir o registro "+id+" ?");
                if (resposta == 0) // ) - Yes, 1 - no, 2 - cancel
                {
                    // Realizando a exclusão dos dados
                    ManicureDAO manicureDao = new ManicureDAO();
                    manicureDao.excluir(Integer.parseInt(id));
                    JOptionPane.showMessageDialog(this,"Registro excluido com sucesso !");
                    // atualizadn a tabela
                    btPesquisarActionPerformed(evt);
                }
                
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(this,"Ocorreu uma falha : \n"+e.getMessage());
        }
    }//GEN-LAST:event_btExcluirActionPerformed

    private void btEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEditarActionPerformed
        // Verificar se alguma linha da tabela foi selecionada
        int linhaSelecionada = tblManicure.getSelectedRow();
        
        if(linhaSelecionada >= 0){
            try{
                // Pega o ID da primeira coluna (linha selecionada, coluna 0)
                int id = Integer.parseInt(tblManicure.getValueAt(linhaSelecionada, 0).toString());
                
                // Busca o objeto Manicure completo no banco de dados pelo ID
                ManicureDAO dao  = new ManicureDAO();
                Manicure manicureSelecionada = dao.obter(id);
                
                // Abre a tela de Cadastro/Edição e envia os dados para preenchimento
                cadastroManicure cadastro = new cadastroManicure();
                cadastro.preencherEdicao(manicureSelecionada);
                cadastro.setVisible(true);
            }catch(Exception e){
                JOptionPane.showMessageDialog(this,"Erro ao selecionar manicure : "+ e.getMessage());
            }
        }else {
            JOptionPane.showMessageDialog(this,"Por favor, selecionar uma manicure na tela para editar.");
        }
    }//GEN-LAST:event_btEditarActionPerformed

