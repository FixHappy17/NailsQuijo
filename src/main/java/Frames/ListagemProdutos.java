public void preencherTabela(List<Produtos>produtos){
    String columns[] = {"ID","Nome","Marca","Categoria","Quantidade"};
    
    if(produtos != null){
        String dados[][] = new String [produtos.size()][columns.length];
        int i = 0;
        for(Produtos p : produtos){
            dados[i] = new String[]{
               String.valueOf(p.getIdProdutos()),
                p.getNome(),
                p.getMarca(),
                p.getCategoria(),
               p.getQuantidade()!= null ? String.valueOf(p.getQuantidade()) :""
            };
            i++;
            }
        DefaultTableModel model = new DefaultTableModel(dados,columns);
        tblProdutos.setModel(model);
        }
    }


