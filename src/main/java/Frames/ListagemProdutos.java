    private void btExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btExcluirActionPerformed
        try{
            if(tblProdutos.getSelectedRow() >= 0){ // verificar se algo foi selecionado na tabela 
                String id = tblProdutos.getValueAt(tblProdutos.getSelectedRow(),0).toString();
                
                // Janela de confirmação
                int resposta = JOptionPane.showConfirmDialog(this,"Deseja mesmo excluir o registro : "+id+" ?");
                if (resposta == 0) // 0 - Yes, 1 - no, 2- cancel
                {
                                   // Realizando a exclusão dos dados
                    ProdutosDAO dao = new ProdutosDAO();
                dao.excluir(Integer.parseInt(id));
                JOptionPane.showMessageDialog(this,"Registro excluido com sucesso !");
                
                // Atualizando a tabela
                btPesquisarActionPerformed(evt);
                
                
                }
                
            }
        }catch(Exception e){
                    JOptionPane.showMessageDialog(this,"Ocorreu uma falha :\n "+e.getMessage());
                    }
    }//GEN-LAST:event_btExcluirActionPerformed

    private void btEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEditarActionPerformed
        // Verificar se alguma linha da tabela foi selecionada
        int linhaSelecionada = tblProdutos.getSelectedRow();
        
        if(linhaSelecionada >= 0){
            try{
                // Pega o ID da primeira coluna (linha selecionada)
                int id = Integer.parseInt(tblProdutos.getValueAt(linhaSelecionada, 0).toString());
                
                // Busca o produto completo no banco de dados pelo ID
                ProdutosDAO dao = new ProdutosDAO();
                Produtos produtoSelecionado = dao.obter(id);
                
                // Abre a tela de cadastro de produtos e envia os dados para preencher
                CadastroProdutos cadastro = new CadastroProdutos();
                cadastro.preencherEdicao(produtoSelecionado);
                cadastro.setVisible(true);
                
            }catch(Exception e){
                JOptionPane.showMessageDialog(this,"Erro ao selecionar o produto : "+e.getMessage());
            }
            
        }else{
            JOptionPane.showMessageDialog(this,"Por favor, selecionar um produto na tabela de produtos para editar");
        }
       
    }//GEN-LAST:event_btEditarActionPerformed

