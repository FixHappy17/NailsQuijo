    private void btPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btPesquisarActionPerformed
        try{
            ProdutosDAO dao = new ProdutosDAO();
            String nome = txtNome.getText();
            String marca = txtMarca.getText();
            String categoria = txtCategoria.getText();
            String qtdTexto = txtQuantidade.getText().trim();
            Integer quantidade = qtdTexto.isEmpty() ? null : Integer.parseInt(qtdTexto);
            
            List<Produtos> produtos = dao.listar(nome,marca,categoria,quantidade);
            
            preencherTabela(produtos);
           
        }catch(Exception e){
            JOptionPane.showMessageDialog(this,"Ocoreeu uma falha: \n"+e.getMessage());
        }
    }//GEN-LAST:event_btPesquisarActionPerformed

