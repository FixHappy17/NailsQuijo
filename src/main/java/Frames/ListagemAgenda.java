    private void EditarStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditarStatusActionPerformed
         int linhaSelecionada = tblAgenda.getSelectedRow();
        
        if(linhaSelecionada == -1){
            JOptionPane.showMessageDialog(this,"Selecione um agendamento na tabela primeiro.");
            return ;
        }
        
        // Pega o ID do agendamento e o status atual
        int idAgenda = (int) tblAgenda.getValueAt(linhaSelecionada,0);
        String statusAtual = tblAgenda.getValueAt(linhaSelecionada,7).toString();
        
        // Altera o status de sim para não e vice-versa
        String novoStatus = statusAtual.equalsIgnoreCase("Sim")? "Não" : "Sim";
        
        int confirma = JOptionPane.showConfirmDialog(this,
                "Deseja alterar o status do agendamento : "+idAgenda+" Para "+novoStatus+" ?",
        "Confirmar Alteração",JOptionPane.YES_NO_OPTION);
        
        
        
        if(confirma == JOptionPane.YES_NO_OPTION){
            try{
                AgendaDAO dao = new AgendaDAO();
                dao.atualizarStatus(idAgenda, novoStatus);
                
                JOptionPane.showMessageDialog(this,"Status atualizado com sucesso !");
                
                preencherTabela(txtCliente.getText(), txtProcedimento.getText());
                
            }catch(Exception e){
                JOptionPane.showMessageDialog(this,"Erro ao atualizar status: "+ e.getMessage());
            }
        }
    }//GEN-LAST:event_EditarStatusActionPerformed

