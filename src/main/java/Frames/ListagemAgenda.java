    private void btExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btExcluirActionPerformed
       try{
           if(tblAgenda.getSelectedRow() >= 0 ){ // Verifica se tem algum objeto selecionado
               String id = tblAgenda.getValueAt(tblAgenda.getSelectedRow(), 0).toString();
               
               // Janela de confirmação
               int resposta = JOptionPane.showConfirmDialog(this,"Deseja mesmo excluir o registro : "+id+" ?");
               if(resposta == 0){
                   AgendaDAO agendaDao = new AgendaDAO();
                   agendaDao.excluir(Integer.parseInt(id));
                   JOptionPane.showMessageDialog(this,"Registro excluído com sucesso !");
                   btPesquisarActionPerformed(evt);
               }
           
       }
       }catch(Exception e){
           JOptionPane.showMessageDialog(this,"Ocorreu uma falha : "+e.getMessage());
       }
    }//GEN-LAST:event_btExcluirActionPerformed

