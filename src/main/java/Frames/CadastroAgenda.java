    private void btAgendarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btAgendarActionPerformed
      try {
        Console.Agenda agenda = new Console.Agenda();

        // Data
        java.text.SimpleDateFormat sdfData = new java.text.SimpleDateFormat("dd/MM/yyyy");
        sdfData.setLenient(false);
        java.util.Date data = sdfData.parse(fmtData.getText());
        agenda.setAgendamento(data);

        // Horário
        java.text.SimpleDateFormat sdfHora = new java.text.SimpleDateFormat("HH:mm");
        java.util.Date horaParsed = sdfHora.parse(fmtHorario.getText());
        agenda.setHorario(new java.sql.Time(horaParsed.getTime()));

        // Chaves Estrangeiras (Relacionamentos)
        agenda.setCliente((Console.Cliente) cbCliente.getSelectedItem());
        agenda.setManicure((Console.Manicure) cbManicure.getSelectedItem());
        
        // Corrigido de setProcedimento para setServico
        agenda.setServico((Console.Servicos) cbServico.getSelectedItem());

        // Gravação via DAO
        ConsoleDAO.AgendaDAO dao = new ConsoleDAO.AgendaDAO();
        dao.cadastrar(agenda);

        javax.swing.JOptionPane.showMessageDialog(this, "Agendamento realizado com sucesso!");
        limparCampos();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao agendar: " + e.getMessage());
    }
    }//GEN-LAST:event_btAgendarActionPerformed

