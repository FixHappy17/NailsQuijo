    private int idAgendaEdicao = 0;
    
    public void preencherEdicao(Agenda a){
        this.idAgendaEdicao = a.getIdAgenda();
        
        cbCliente.setSelectedItem(a.getCliente());
        cbManicure.setSelectedItem(a.getManicure());
        cbServico.setSelectedItem(a.getServico());
        
        SimpleDateFormat sdfData = new SimpleDateFormat("dd/MM/yy");
        SimpleDateFormat sdfHora = new SimpleDateFormat("HH:mm");
        
        if (a.getAgendamento() != null){
            fmtData.setText(sdfData.format(a.getAgendamento()));
            fmtHorario.setText(sdfHora.format(a.getHorario()));
        }
        
        btAgendar.setText("Atualizar");
        
        agendaEdicao = a;
        
        
    }
    
    
    
    
    private void carregarCombos() {
        cbCliente.removeAllItems();
        cbManicure.removeAllItems();
        cbServico.removeAllItems();

        try {
            ClienteDAO cDAO = new ClienteDAO();
            for (Cliente c : cDAO.listar()) {
                cbCliente.addItem(c);
            }

            ManicureDAO mDAO = new ManicureDAO();
            for (Manicure m : mDAO.listar()) {
                cbManicure.addItem(m);
            }

            ServicosDAO sDAO = new ServicosDAO();
            for (Servicos s : sDAO.listar()) {
                cbServico.addItem(s);
            }

            atualizarValorServico();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar listas: " + e.getMessage());
        }
    }
    
    private void atualizarValorServico() {
    Console.Servicos s = (Console.Servicos) cbServico.getSelectedItem();
    if (s != null && s.getValor() != null) {
        lbValor.setText(String.format("R$ %.2f", s.getValor()));
    } else {
        lbValor.setText("R$ 0,00");
    }
}
    private void limparCampos() {
    fmtData.setText("");
    fmtHorario.setText("");
    lbValor.setText("0");
    if (cbCliente.getItemCount() > 0) cbCliente.setSelectedIndex(0);
    if (cbManicure.getItemCount() > 0) cbManicure.setSelectedIndex(0);
    if (cbServico.getItemCount() > 0) cbServico.setSelectedIndex(0);
}
    
    

